#!/usr/bin/env node
// Renders the winget manifest set (ManifestVersion 1.6.0) for Kotilo.KotiloDeck.
//
//   node scripts/winget-manifest.mjs 1.0.0 "src-tauri/target/release/bundle/nsis/Kotilo Deck_1.0.0_x64-setup.exe"
//   node scripts/winget-manifest.mjs 1.0.0 https://github.com/kotilo-dev/kotilo-deck/releases/download/v1.0.0/Kotilo.Deck_1.0.0_x64-setup.exe
//   node scripts/winget-manifest.mjs 1.0.0 placeholder      # no hash (template)
//
// Options: --out <dir> (default packaging/winget), --date YYYY-MM-DD (default today, UTC).
// A local path is hashed as is; the InstallerUrl is still the GitHub release asset, so hash
// the exact file you uploaded. A URL is downloaded and hashed, and used as InstallerUrl.
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ID = 'Kotilo.KotiloDeck';
const REPO = 'https://github.com/kotilo-dev/kotilo-deck';
const MANIFEST_VERSION = '1.6.0';

const args = process.argv.slice(2);
const opt = (/** @type {string} */ name) => {
	const i = args.indexOf(name);
	if (i === -1) return undefined;
	const [, value] = args.splice(i, 2);
	return value;
};
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = resolve(opt('--out') ?? join(root, 'packaging', 'winget'));
const releaseDate = opt('--date') ?? new Date().toISOString().slice(0, 10);
const [rawVersion, source] = args;
if (!rawVersion || !source) {
	console.error(
		'usage: winget-manifest.mjs <version> <installer-path|installer-url|placeholder> [--out dir] [--date YYYY-MM-DD]'
	);
	process.exit(2);
}
const version = rawVersion.replace(/^v/, '');
if (!/^\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?$/.test(version)) {
	console.error(`winget-manifest: "${rawVersion}" is not a SemVer version`);
	process.exit(2);
}
if (!/^\d{4}-\d{2}-\d{2}$/.test(releaseDate)) {
	console.error(`winget-manifest: --date must be YYYY-MM-DD`);
	process.exit(2);
}

// Tauri names the NSIS bundle "Kotilo Deck_<v>_x64-setup.exe"; GitHub turns the space into a dot.
let installerUrl = `${REPO}/releases/download/v${version}/Kotilo.Deck_${version}_x64-setup.exe`;
let sha256;
if (source === 'placeholder') {
	sha256 = '<INSTALLER-SHA256>';
} else if (/^https?:\/\//.test(source)) {
	installerUrl = source;
	const res = await fetch(source, { redirect: 'follow' });
	if (!res.ok) {
		console.error(`winget-manifest: GET ${source} -> ${res.status}`);
		process.exit(1);
	}
	sha256 = sha(Buffer.from(await res.arrayBuffer()));
} else {
	sha256 = sha(readFileSync(source));
}

/** @param {Buffer} buf */
function sha(buf) {
	return createHash('sha256').update(buf).digest('hex').toUpperCase();
}

const header = (/** @type {string} */ type) =>
	`# yaml-language-server: $schema=https://aka.ms/winget-manifest.${type}.${MANIFEST_VERSION}.schema.json\n` +
	`# Generated by scripts/winget-manifest.mjs - edit the script, not this file.\n\n`;

const files = {
	[`${ID}.yaml`]:
		header('version') +
		`PackageIdentifier: ${ID}
PackageVersion: ${version}
DefaultLocale: en-US
ManifestType: version
ManifestVersion: ${MANIFEST_VERSION}
`,
	[`${ID}.installer.yaml`]:
		header('installer') +
		`PackageIdentifier: ${ID}
PackageVersion: ${version}
Platform:
  - Windows.Desktop
MinimumOSVersion: 10.0.17763.0
InstallerType: nullsoft
Scope: user
InstallModes:
  - interactive
  - silent
  - silentWithProgress
UpgradeBehavior: install
# Tauri's NSIS installer registers HKCU\\...\\Uninstall\\<productName>.
ProductCode: Kotilo Deck
ReleaseDate: ${releaseDate}
Installers:
  - Architecture: x64
    InstallerUrl: ${installerUrl}
    InstallerSha256: ${sha256}
ManifestType: installer
ManifestVersion: ${MANIFEST_VERSION}
`,
	[`${ID}.locale.en-US.yaml`]:
		header('defaultLocale') +
		`PackageIdentifier: ${ID}
PackageVersion: ${version}
PackageLocale: en-US
Publisher: Kotilo
PublisherUrl: https://kotilo.dev
PublisherSupportUrl: ${REPO}/issues
Author: Kotilo
PackageName: Kotilo Deck
PackageUrl: ${REPO}
License: MIT
LicenseUrl: ${REPO}/blob/main/LICENSE
Copyright: Copyright (c) 2026 Kotilo
ShortDescription: Full-screen developer dashboard for a secondary display.
Description: |-
  Kotilo Deck turns a secondary display, a small USB screen or an old tablet into a glanceable
  dashboard: clock, weather, calendar, system load, volume and media controls, pomodoro, todos
  and your AI agents, in every popular developer colour theme.
Moniker: kotilo-deck
Tags:
  - dashboard
  - developer-tools
  - pomodoro
  - second-screen
  - widgets
ReleaseNotesUrl: ${REPO}/releases/tag/v${version}
ManifestType: defaultLocale
ManifestVersion: ${MANIFEST_VERSION}
`
};

mkdirSync(outDir, { recursive: true });
for (const [name, text] of Object.entries(files)) {
	writeFileSync(join(outDir, name), text);
	console.log(join(outDir, name));
}
console.log(`InstallerSha256: ${sha256}`);
